const assert=require('node:assert/strict');
const api=require('../domain-core-v126-nutrition.js');
const n=api.calculate({kcal:'200',p:'10',c:'5,5',f:'0'},150);
assert.deepEqual(n,{known:{kcal:true,p:true,c:true,f:true},kcal:300,p:15,c:8.25,f:0,complete:true});
const partial=api.calculate({kcal:'200',p:'',c:'0'},150);
assert.equal(partial.p,null);
assert.equal(partial.c,0);
assert.equal(partial.complete,false);
assert.equal(api.calculate({kcal:200,p:10,c:5,f:0},150,'total').kcal,200);
assert.throws(()=>api.calculate({kcal:-1},100));
assert.throws(()=>api.calculate({kcal:200},0));
assert.throws(()=>api.calculate({kcal:200},'NaN'));
const rows=[{member_id:'simona',data:'2026-10-11',kcal:300,proteine_g:15,carboidrati_g:8.25,grassi_g:0,v126Known:n.known},{member_id:'simona',data:'2026-10-11',kcal:100,proteine_g:null,carboidrati_g:0,grassi_g:null,v126Known:partial.known},{member_id:'bimbo',data:'2026-10-11',kcal:999,v126Known:{kcal:true}},{member_id:'simona',data:'2026-10-10',kcal:999,v126Known:{kcal:true}},{member_id:'tutti',data:'2026-10-11',kcal:999,v126Known:{kcal:true}}];
const t=api.totals(rows,'simona','2026-10-11');
assert.equal(t.count,2);
assert.equal(t.kcal,400);
assert.equal(t.f,0);
assert.equal(t.known.f,1,'Uno zero dichiarato è conosciuto');
assert.equal(t.missing.f,1);
assert.equal(t.incomplete,1);
assert.equal(api.knownValue({grassi_g:0,nutrizione_compilata:true},'f'),null,'Uno zero storico non documentato non deve sembrare completo');
assert.equal(api.localDate(new Date('2026-10-10T22:30:00Z')),'2026-10-11','Usare Europe/Rome, non UTC');
assert.equal(api.validDate('2026-02-31'),false);
assert.equal(api.validDate('2026-10-11'),true);
assert.equal(api.extractGtin('(01)08012345678901(10)LOTTO'),'08012345678901');
assert.equal(api.extractGtin('https://example.test/01/08012345678901/10/lotto'),'08012345678901');
assert.equal(api.extractGtin('https://example.test/?ean=8012345678901'),'8012345678901');
assert.equal(api.extractGtin('https://example.test/menu'),'');
assert.deepEqual(api.productNutrients({nutriments:{'energy-kcal_100g':0,proteins_100g:0,carbohydrates_100g:0,fat_100g:0}}),{kcal:0,p:0,c:0,f:0});
assert.equal(api.productNutrients({nutriments:{'energy-kj_100g':418.4}}).kcal,100);
assert.equal(api.hasTerm('pasta al pesto','pasta al pesto'),true);
assert.equal(api.hasTerm('sorriso','riso'),false);
const recipes=[{id:'a',nome:'Pasta al pesto',ingredienti:['pasta','pesto'],minuti:15},{id:'b',nome:'Risotto ai funghi',ingredienti:['riso','funghi'],minuti:20},{id:'c',nome:'Pasta lunga',ingredienti:['pasta'],minuti:60}];
const child={id:'bimbo',nome:'Bimbo',ingredientiPreferiti:['pesto'],ingredientiNonGraditi:['funghi'],piattiPreferiti:['pasta al pesto'],piattiNonGraditi:[]};
const ranking=api.recommend(recipes,[child],[],[],'2026-10-11',30);
assert.equal(ranking.length,1,'Escludere non graditi e ricette troppo lunghe dagli spunti');
assert.equal(ranking[0].recipe.id,'a');
assert.equal(api.recommend(recipes,[{...child,piattiNonGraditi:['pasta al pesto']}],[],[],'2026-10-11',30).length,0);
assert.equal(recipes.length,3,'I gusti non eliminano ricette dal catalogo');
const plan={id:'test',week:[{day:'Lunedì',meals:[{name:'Pranzo',components:[{kind:'ingredient',id:'pollo',name:'Pollo',amount:150,unit:'g'},{kind:'ingredient',id:'uovo',name:'Uova',amount:2,unit:'uova'}]}]}]};
const nutrition={['pollo|']:{values:{kcal:100,p:20,c:0,f:1},unita:'g'},['uova|']:{values:{kcal:200,p:15,c:0,f:10},unita:'g'}};
let menu=api.dietTotals(0,plan,{},nutrition);
assert.equal(menu.kcal,150);
assert.equal(menu.complete,false,'Pezzi non pesati non danno un obiettivo calorico completo');
assert.equal(menu.missingWeights,1);
menu=api.dietTotals('Lunedì',plan,{quantities:{'0|0|uovo|uovo':100}},nutrition);
assert.equal(menu.kcal,350);
assert.equal(menu.complete,true);
assert.equal(menu.c,0,'Zero carboidrati documentato resta valido');
menu=api.dietTotals(0,plan,{quantities:{'0|0|uovo|uovo':100}},{...nutrition,['uova|']:{values:{kcal:200},unita:'g'}});
assert.equal(menu.caloriesComplete,true);
assert.equal(menu.complete,false,'Macro mancanti restano parziali anche se le calorie sono presenti');
