const assert=require('node:assert/strict');
const Q=require('../domain-core-v124-diet-shopping.js');
const old=require('../domain-core-v125-default-diet.js').getDefaultDiet();
const api=require('../domain-core-v126-diet.js');
const diet=api.getDiet();
assert.equal(diet.primaryPlan,'simona-principale');
assert.equal(diet.title,'Piano alimentare');
assert.equal(diet.sourceContacts,undefined);
assert(!/Serinelli|Carreri|icloud|345843/.test(JSON.stringify(diet)));
const main=diet.plans.find(p=>p.id===api.mainId),original=diet.plans.find(p=>p.id===api.originalId);
assert.deepEqual(original.week,old.week,'Il documento originale rimane identico');
assert.deepEqual(diet.week,main.week);
assert.deepEqual([0,3,5].map(d=>main.week[d].meals[4].components[0].name),['Platessa','Pesce spada','Polpo']);
for(let d=0;d<7;d++)for(let m=0;m<5;m++){
  const before=structuredClone(old.week[d].meals[m]),after=structuredClone(main.week[d].meals[m]);
  Q.validateComponents(after.components);
  if(m===4&&[0,3,5].includes(d)){
    assert.equal(after.components[0].amount,150);
    before.items.shift();after.items.shift();before.components.shift();after.components.shift();
  }
  assert.deepEqual(after,before,'Solo i tre pesci richiesti cambiano');
}
assert.equal(main.week.flatMap(d=>d.meals).length,35);
assert.equal(api.getDiet(old).primaryPlan,'simona-principale','Una copia v125 viene migrata');
const validated=structuredClone(old);validated.week.forEach(d=>d.meals.forEach(m=>m.components=Q.validateComponents(m.components)));
assert.equal(api.getDiet(validated).primaryPlan,'simona-principale','Il validatore cambia l’ordine delle proprietà senza cambiare la dieta');
const custom=structuredClone(old);custom.week[0].meals[0].items[1]='Latte 110 g';
assert.deepEqual(api.getDiet(custom),custom,'Una settimana personale modificata viene preservata');
const customComponents=structuredClone(old);customComponents.week[0].meals[0].components[1].amount=110;
assert.deepEqual(api.getDiet(customComponents),customComponents,'Non sostituire componenti personali con lo stesso testo');
const legacy=structuredClone(old);legacy.week.forEach(d=>d.meals.forEach(m=>delete m.components));
assert.equal(api.getDiet(legacy).primaryPlan,'simona-principale','Compatibilità con il vecchio testo senza componenti');
assert.deepEqual(api.getDiet(diet),diet,'La migrazione è idempotente');
const text=api.textForPlan();
assert(text.includes('Platessa 150 g'));assert(text.includes('Pesce spada 150 g'));assert(text.includes('Polpo 150 g'));
assert(!text.includes('Filetto di merluzzo'));assert(!text.includes('Filetto di branzino'));
assert(api.textForPlan(diet,api.originalId).includes('Filetto di merluzzo'));
const scopes=main.week.flatMap((d,di)=>d.meals.map((m,mi)=>[di,mi]));
const batch=api.collect(main,{},'2026-10-05',scopes);
let shopping=api.syncShopping([],batch).items;
assert.equal(shopping.find(x=>x.nome==='Latte parzialmente scremato').quantita,700);
assert.equal(shopping.find(x=>x.nome==='Olio extravergine di oliva').quantita,140);
assert.equal(shopping.find(x=>x.nome==='Pane preferibilmente integrale').quantita,140);
assert.equal(shopping.find(x=>x.nome==='Uova').quantita,4);
assert.equal(shopping.find(x=>x.nome==='Fiori d’acqua Mulino Bianco').quantita,12);
for(const name of ['Platessa','Pesce spada','Polpo'])assert.deepEqual(api.summary(shopping.find(x=>x.nome===name)),{detail:'150 g (× 1)',total:'Totale 150 g'});
assert.deepEqual(api.syncShopping(shopping,batch).items,shopping,'Ripetere una settimana non duplica');
const repeated={scopeKeys:['w|1','w|2','w|3'],portions:[1,2,3].map(i=>({scopeKey:'w|'+i,sourceKey:'w|'+i+'|pesce',name:'Platessa',amount:150,unit:'g',basis:'',label:'Pasto '+i}))};
assert.deepEqual(api.summary(api.syncShopping([],repeated).items[0]),{detail:'150 g (× 3)',total:'Totale 450 g'});
const state={choices:{'1|4|pane-pasta':'pasta','0|1|yogurt-kefir':'kefir','6|2|piatto-domenica':'risotto-sogliola'},
  quantities:{'0|4|finocchi|finocchi':200,'1|4|uova|uova':110,'0|3|frutta|medio|frutta':180},optional:{}};
const changed=api.syncShopping([],api.collect(main,state,'2026-10-05',scopes)).items;
assert.equal(changed.find(x=>x.nome==='Pasta preferibilmente integrale').quantita,60);
assert.equal(changed.find(x=>x.nome==='Pane preferibilmente integrale').quantita,70);
assert.equal(changed.find(x=>x.nome==='Kefir bianco da bere').quantita,300);
assert.equal(changed.find(x=>x.nome==='Yogurt greco bianco intero 5%').quantita,900);
assert(!changed.some(x=>x.nome==='Tonno'));
assert(changed.some(x=>x.nome==='Sogliola'));
assert.equal(changed.find(x=>x.nome==='Uova'&&x.unita==='g').quantita,110);
assert.equal(changed.find(x=>x.nome==='Uova'&&x.unita==='pezzi').quantita,2);
const eggs=api.selectedIngredients(main.week[1].meals[4],1,4,state).find(x=>x.name==='Uova');
assert.equal(eggs.amount,110);assert.equal(eggs.unit,'g');assert.equal(eggs.prescribedAmount,2);assert.equal(eggs.prescribedUnit,'pezzi');
assert.equal(changed.find(x=>x.nome==='Finocchi'&&x.unita==='g').quantita,200);
assert.equal(api.summary(changed.find(x=>x.nome==='Finocchi'&&x.unita==='q.b.')).total,'Totale da indicare');
const oldBatch=Q.collect(old.plans[0],{},'2026-10-05',scopes);
const manual={id:'manual',nome:'Filetto di merluzzo',quantita:250,unita:'g',stato:'da_comprare',origini:['Inserimento manuale']};
const pending=Q.syncShopping([manual],oldBatch).items;
const migrated=api.migrateShopping(pending,{},main);
assert.equal(migrated.find(x=>x.nome==='Filetto di merluzzo').quantita,250,'La quota manuale va conservata durante il cambio pesce');
assert(!migrated.some(x=>x.nome==='Orata'));
assert(!migrated.some(x=>x.nome==='Filetto di branzino'));
assert.equal(migrated.find(x=>x.nome==='Platessa').quantita,150);
assert.equal(migrated.find(x=>x.nome==='Pesce spada').quantita,150);
assert.equal(migrated.find(x=>x.nome==='Polpo').quantita,150);
assert.deepEqual(api.migrateShopping(migrated,{},main),migrated);
const bought=Q.syncShopping([],oldBatch).items;bought.forEach(x=>x.stato='comprato');
assert.deepEqual(api.migrateShopping(bought,{},main),bought,'La cronologia acquistata resta intatta');
