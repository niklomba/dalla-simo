const assert=require('node:assert/strict');
const api=require('../domain-core-v124-diet-shopping.js');
const portions=[0,1,2].map(i=>({scopeKey:'week|'+i,sourceKey:'week|'+i+'|food',name:'Alimento A',amount:100,unit:'g',basis:'',label:'Pasto '+i}));
const batch={scopeKeys:portions.map(p=>p.scopeKey),portions};
let result=api.syncShopping([],batch);
assert.equal(result.items.length,1);
assert.equal(result.items[0].quantita,300);
assert.deepEqual(api.summary(result.items[0]),{detail:'100 g × 3',total:'Totale 300 g'});
result=api.syncShopping(result.items,batch);
assert.equal(result.items[0].quantita,300,'Una stessa settimana non deve duplicare le porzioni');
const partial=api.syncShopping(result.items,{scopeKeys:['week|0'],portions:[{...portions[0],amount:50}]});
assert.equal(partial.items[0].quantita,250,'Una modifica deve sostituire solo la porzione interessata');
assert.equal(api.summary(partial.items[0]).detail,'100 g × 2 + 50 g × 1');
const manual={id:'manuale',nome:'Alimento A',unita:'kg',quantita:0.5,stato:'da_comprare',origini:['Inserimento manuale']};
const mixed=api.syncShopping([manual],batch);
assert.equal(mixed.items[0].quantita,0.8);
assert.equal(api.summary(mixed.items[0]).total,'Totale 800 g');
const changed=api.syncShopping(mixed.items,{scopeKeys:batch.scopeKeys,portions:portions.map(p=>({...p,name:'Alimento B'}))});
assert.equal(changed.items.find(x=>x.nome==='Alimento A').quantita,0.5,'La spesa inserita manualmente va conservata');
assert.equal(changed.items.find(x=>x.nome==='Alimento B').quantita,300);
const bought=api.syncShopping([],{scopeKeys:['week|0'],portions:[portions[0]]}).items;
bought[0].stato='comprato';
const afterBuying=api.syncShopping(bought,{scopeKeys:['week|0'],portions:[{...portions[0],amount:150},{...portions[0],name:'Alimento B',sourceKey:'week|0|other'}]});
assert.equal(afterBuying.items.find(x=>x.nome==='Alimento A'&&x.stato==='da_comprare').quantita,50,'Sottrarre solo quanto è già stato acquistato per quella porzione');
assert.equal(afterBuying.items.find(x=>x.nome==='Alimento B').quantita,100,'Un alimento acquistato non deve bloccare gli altri ingredienti del pasto');
assert.equal(api.syncShopping(afterBuying.items,{scopeKeys:['week|0'],portions:[{...portions[0],amount:150}]}).items.find(x=>x.nome==='Alimento A'&&x.stato==='da_comprare').quantita,50);
const unknown=api.syncShopping([],{scopeKeys:['week|q'],portions:[{...portions[0],scopeKey:'week|q',sourceKey:'week|q|food',amount:null,unit:'q.b.'}]});
assert.equal(unknown.items[0].quantita,0);
assert.equal(api.summary(unknown.items[0]).total,'Totale da indicare');
const meal={components:api.validateComponents([{kind:'choice',id:'scelta',label:'Scegli',defaultOption:'prima',options:[{id:'prima',label:'Prima',ingredients:[{kind:'ingredient',id:'a',name:'Alimento A',amount:100,unit:'g'}]},{id:'seconda',label:'Seconda',ingredients:[{kind:'ingredient',id:'b',name:'Alimento B',amount:200,unit:'g'}]}]}])};
assert.equal(api.selectedIngredients(meal,0,0,{choices:{'0|0|scelta':'seconda'}}).length,1);
assert.equal(api.selectedIngredients(meal,0,0,{choices:{'0|0|scelta':'seconda'}})[0].name,'Alimento B');
assert.throws(()=>api.validateComponents([{kind:'ingredient',id:'bad',name:'Alimento A',amount:-1,unit:'g'}]));
console.log('DIET_PORTIONS_OK: somme, idempotenza, modifiche, unità, dati manuali e scelte');
